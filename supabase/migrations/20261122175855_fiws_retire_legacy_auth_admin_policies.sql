begin;
drop policy if exists "Admins manage settings" on public.site_settings;
drop policy if exists "Admins insert settings" on public.site_settings;
drop policy if exists "Admins update settings" on public.site_settings;
drop policy if exists "Admins delete settings" on public.site_settings;
revoke insert,update,delete on public.site_settings from anon,authenticated;
grant select on public.site_settings to anon,authenticated;
drop policy if exists "Applicants read their own application" on public.applications;
create policy "Applicants read their own application" on public.applications for select to authenticated using ((select auth.uid())=applicant_id);
drop policy if exists "Admins update applications" on public.applications;
drop policy if exists "Admins delete applications" on public.applications;
revoke update,delete on public.applications from anon,authenticated;
grant select,insert on public.applications to authenticated;
drop policy if exists "Admins read audit log" on public.admin_audit_log;
revoke all on public.admin_audit_log from anon,authenticated;
drop policy if exists "FIWS admins upload public assets" on storage.objects;
drop policy if exists "FIWS admins update public assets" on storage.objects;
drop policy if exists "FIWS admins delete public assets" on storage.objects;
revoke insert,update,delete on storage.objects from anon,authenticated;
commit;